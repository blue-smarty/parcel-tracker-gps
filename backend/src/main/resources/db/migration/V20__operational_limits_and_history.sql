CREATE TABLE operational_settings (
    id varchar(255) PRIMARY KEY,
    max_items_per_booking integer NOT NULL,
    max_package_lines integer NOT NULL,
    max_quantity_per_item integer NOT NULL,
    max_item_weight_kg double precision NOT NULL,
    max_dimension_cm double precision NOT NULL,
    booking_cutoff time NOT NULL,
    time_zone varchar(255) NOT NULL,
    max_schedule_days_ahead integer NOT NULL,
    delivery_windows jsonb NOT NULL,
    stale_assignment_enabled boolean NOT NULL,
    stale_assignment_minutes integer NOT NULL,
    unassign_stale_assignments boolean NOT NULL
);

